const PRINCIPAL_ICON = { user: UserIcon, group: UsersIcon, everyone: GlobeIcon } as const;

const EXPIRY = [
  { label: t("No expiration"), days: 0 },
  { label: t("{n} day|{n} days", { n: 7 }), days: 7 },
  { label: t("{n} day|{n} days", { n: 30 }), days: 30 },
  { label: t("{n} day|{n} days", { n: 90 }), days: 90 },
];

/** Names of "Everyone" and deleted principals are generated by the server and need translating; account and group names stay as-is */
/** Role shown next to a user in search results (the server sends "Administrator" or "User"; the list uses the short "Admin") */
const roleDetail = (detail: string) => (detail === "Administrator" ? t("Admin") : tServer(detail));
const principalName = (g: Grant) => (g.principal_type === "everyone" || g.principal_name === "(deleted)" ? tServer(g.principal_name) : g.principal_name);

function PrincipalPicker(props: { value: Principal | null; onChange(p: Principal | null): void; allowEveryone: boolean }) {
  const [q, setQ] = useState("");
  const [debounced, setDebounced] = useState("");
  const [open, setOpen] = useState(false);
  /** The option the arrows are on */
  const [active, setActive] = useState(0);
  const listId = useId();
  /** Where the focus goes once the box or the choice in its place is shown */
  const refocus = useRef<"next" | "box" | null>(null);
  const place = useRef<HTMLDivElement>(null);
  useLayoutEffect(() => {
    const to = refocus.current;
    refocus.current = null;
    if (to === "next") place.current?.parentElement?.querySelector("select")?.focus();
    else if (to === "box") place.current?.querySelector("input")?.focus();
  }, [props.value]);
  useEffect(() => {
    const timer = setTimeout(() => setDebounced(q), 200);
    return () => clearTimeout(timer);
  }, [q]);
  const results = useQuery({ queryKey: keys.directory(debounced), queryFn: () => api.directory(debounced), enabled: open });
  const options: Principal[] = [
    ...(props.allowEveryone && t("Everyone").toLowerCase().includes(q.trim().toLowerCase())
      ? [{ guest: false, principal_type: "everyone" as const, principal_id: 0, name: t("Everyone"), detail: t("All users") }]
      : []),
    ...(results.data ?? []),
  ];

  if (props.value) {
    const Icon = PRINCIPAL_ICON[props.value.principal_type];
    return (
      <div ref={place} className="flex h-8 min-w-0 flex-1 basis-full items-center gap-2 rounded-md border bg-muted/50 px-2 text-sm sm:basis-0">
        <Icon className="size-4 shrink-0 text-muted-foreground" />
        <span className="truncate">{props.value.name}</span>
        <button
          type="button"
          className="ml-auto text-muted-foreground hover:text-foreground"
          aria-label={t("Choose again")}
          onClick={() => {
            refocus.current = "box";
            props.onChange(null);
          }}
        >
          <XIcon className="size-3.5" />
        </button>
      </div>
    );
  }
  const shown = open && options.length > 0;
  const current = Math.min(active, options.length - 1);
  const pick = (o: Principal) => {
    // The box goes: the focus moves on to the role
    refocus.current = "next";
    props.onChange(o);
    setQ("");
    setOpen(false);
  };
  // A combobox: the focus stays in the box, the arrows go through the people and groups found, Enter picks one,
  // Escape closes the list (a second Escape, the dialog)
  const onKeyDown = (e: KeyboardEvent<HTMLInputElement>) => {
    if (e.key === "ArrowDown" || e.key === "ArrowUp") {
      e.preventDefault();
      if (!shown) {
        setOpen(true);
        setActive(e.key === "ArrowDown" ? 0 : options.length - 1);
      } else setActive((current + (e.key === "ArrowDown" ? 1 : -1) + options.length) % options.length);
    } else if (e.key === "Enter" && shown && current >= 0) {
      e.preventDefault();
      pick(options[current]);
    } else if (e.key === "Escape" && shown) {
      e.preventDefault();
      e.stopPropagation();
      setOpen(false);
    }
  };
  const optionId = (i: number) => `${listId}-${i}`;
  return (
    <div ref={place} className="min-w-0 flex-1 basis-full sm:basis-0">
      <Input
        role="combobox"
        aria-label={t("Username or group name")}
        aria-expanded={shown}
        aria-controls={listId}
        aria-autocomplete="list"
        aria-activedescendant={shown && current >= 0 ? optionId(current) : undefined}
        value={q}
        onChange={(e) => {
          setQ(e.target.value);
          setOpen(true);
          setActive(0);
        }}
        onFocus={() => setOpen(true)}
        onBlur={() => setOpen(false)}
        onKeyDown={onKeyDown}
        placeholder={t("Enter a username or group name")}
        className="h-8 text-sm"
      />
      {/* In the dialog's flow (not over it), so a dialog that scrolls doesn't cut it off */}
      <div id={listId} role="listbox" aria-label={t("People and groups")} hidden={!shown} className="mt-1 max-h-56 overflow-y-auto rounded-md border bg-popover p-1 shadow-md">
        {shown &&
          options.map((o, i) => {
            const Icon = PRINCIPAL_ICON[o.principal_type];
            return (
              <div
                key={`${o.principal_type}-${o.principal_id}`}
                id={optionId(i)}
                role="option"
                aria-selected={i === current}
                ref={(el) => {
                  if (el && i === current) el.scrollIntoView({ block: "nearest" });
                }}
                // The focus stays in the box
                onMouseDown={(e) => e.preventDefault()}
                onMouseMove={() => setActive(i)}
                onClick={() => pick(o)}
                className={cn("flex w-full cursor-default items-center gap-2 rounded px-2 py-1.5 text-left text-sm", i === current && "bg-accent")}
              >
                <Icon className="size-4 shrink-0 text-muted-foreground" />
                {/* The whole name, on two lines if it must: a cut-off name can't tell similar ones apart */}
                <span className="min-w-0 flex-1 [overflow-wrap:anywhere]">{o.name}</span>
                <span className="shrink-0 text-xs text-muted-foreground">{o.principal_type === "group" ? `${t("Groups")} · ${tServer(o.detail)}` : roleDetail(o.detail)}</span>
                {o.guest && o.principal_type === "group" && <span className="text-xs text-muted-foreground">{t("Includes guests")}</span>}
              </div>
            );
          })}
      </div>
    </div>
  );
}

function GrantRow(props: {
  g: Grant;
  editable: boolean;
  roles: Role[];
  onRole?(r: Role): void;
  onExpiry?(expiry: number | null): void;
  pending?: boolean;
  maxDays?: number;
  onRemove?(): void;
  removeLabel?: string;
}) {
  const { g } = props;
  const Icon = PRINCIPAL_ICON[g.principal_type];
  return (
    <div className="flex flex-wrap items-center gap-2.5 py-2">
      <span className="flex size-8 shrink-0 items-center justify-center rounded-full bg-muted">
        <Icon className="size-4 text-muted-foreground" />
      </span>
      <div className="min-w-0 flex-1">
        <div className="truncate text-sm">
          {principalName(g)}
          {g.principal_type === "group" && <span className="ml-1.5 text-xs text-muted-foreground">{t("Groups")}</span>}
          {g.guest && <span className="ml-1.5 text-xs text-muted-foreground">{g.principal_type === "group" ? t("Includes guests") : t("Guest")}</span>}
        </div>
        <div className="truncate text-xs text-muted-foreground">
          {g.inherited_from ? t("Inherited from “{name}”", { name: g.inherited_from }) : g.granted_by_name ? t("Granted by {name}", { name: g.granted_by_name }) : t("System default")}
          {g.expires_at && ` · ${tc("date", "Expires {date}", { date: formatDate(g.expires_at) })}`}
        </div>
      </div>
      {props.editable && props.onRole ? (
        <NativeSelect size="sm" value={g.role} onChange={(e) => props.onRole!(e.target.value as Role)} aria-label={t("Role")}>
          {props.roles.map((r) => (
            <option key={r} value={r}>
              {ROLE_LABEL[r]}
            </option>
          ))}
        </NativeSelect>
      ) : (
        <span className="text-xs text-muted-foreground">{ROLE_LABEL[g.role]}</span>
      )}
      {props.onRemove && (
        <Button size="icon-sm" variant="ghost" title={props.removeLabel ?? t("Remove")} aria-label={props.removeLabel ?? t("Remove")} onClick={props.onRemove}>
          <XIcon />
        </Button>
      )}
      {props.editable && props.onExpiry && (
        <GrantExpiry key={`${g.id}-${g.expires_at}`} expiry={g.expires_at} guest={g.guest} maxDays={props.maxDays ?? 90} pending={!!props.pending} onSave={props.onExpiry} />
      )}
    </div>
  );
}

/** Manage access: space root folder = space members; other folders / files = sharing */
/**
 * Who may make share links of the space's items: chosen by its managers (and administrators), who are told first how
 * many links working now would stop; shown to everyone else
 */
function LinkMakersSetting({ driveId, value, canChoose }: { driveId: string; value: LinkMakers; canChoose: boolean }) {
  const qc = useQueryClient();
  const id = useId();
  const stopping = useQuery({ queryKey: ["links-stopping", driveId], queryFn: () => api.linksStopping(driveId), enabled: canChoose });
  const [ask, question] = useConfirm();
  const save = useMutation({
    mutationFn: (makers: LinkMakers) => api.updateDrive(driveId, { link_makers: makers }),
    onSuccess: () => {
      // The space's links, and what the items in it offer (Create share link)
      void invalidate(qc, ...affected.space(), ["node"], ["access"], ["links-stopping", driveId]);
      toast.success(t("Saved"));
    },
    onError: (e) => toast.error(e.message),
  });
  const choose = async (makers: LinkMakers) => {
    const stops = makers === "editors" ? 0 : (stopping.data?.[makers] ?? 0);
    if (
      stops > 0 &&
      !(await ask({
        title: t("Stop {n} share link?|Stop {n} share links?", { n: stops }),
        description: t("They were made by people this no longer allows. They stop working now, and work again if you change this back."),
        confirmText: t("Change"),
        destructive: true,
      }))
    )
      return;
    save.mutate(makers);
  };
  if (!canChoose) return <p className="text-xs text-muted-foreground">{t("Share links can be made by: {who}", { who: LINK_MAKERS_LABEL[value] })}</p>;
  return (
    <div className="grid gap-1.5 border-t pt-3">
      {question}
      <label htmlFor={id} className="text-sm font-medium">
        {t("Share links can be made by")}
      </label>
      <NativeSelect id={id} size="sm" value={value} disabled={save.isPending} onChange={(e) => void choose(e.target.value as LinkMakers)}>
        {(Object.keys(LINK_MAKERS_LABEL) as LinkMakers[]).map((m) => (
          <option key={m} value={m}>
            {LINK_MAKERS_LABEL[m]}
          </option>
        ))}
      </NativeSelect>
      <p className="text-xs text-muted-foreground">{t("Members can still share items with people (Share with…). Someone whose account may not share makes no links anywhere.")}</p>
    </div>
  );
}

export function AccessDialog({ nodeId, onClose }: { nodeId: string; onClose(): void }) {
  const me = useMe();
  const qc = useQueryClient();
  const q = useQuery({ queryKey: keys.access(nodeId), queryFn: () => api.access(nodeId) });
  const [principal, setPrincipal] = useState<Principal | null>(null);
  const [role, setRole] = useState<Role>("viewer");
  const [days, setDays] = useState(0);

  const refresh = () => {
    void refreshFiles(qc, { access: [nodeId] });
  };

  const add = useMutation({
    mutationFn: (req: { principal_type: PrincipalType; principal_id: number; role: Role; expires_at: number | null }) => api.grant(nodeId, req),
    onSuccess: () => {
      setPrincipal(null);
      refresh();
      toast.success(t("Access updated"));
    },
  });
  const remove = useMutation({
    mutationFn: (id: number) => api.revoke(id),
    onSuccess: () => refresh(),
    onError: (e) => toast.error(e.message),
  });
  const [ask, question] = useConfirm();
  const confirmRemove = async (g: Grant, self: boolean) => {
    const name = info?.is_drive_root ? info.drive.name : (info?.node.name ?? "");
    const ok = await ask(
      self
        ? {
            title: t("Leave “{name}”?", { name }),
            description: t("You'll lose your access to it right away. Only someone who manages it can give it back."),
            confirmText: t("Leave"),
            destructive: true,
          }
        : {
            title: t("Remove access for {name}?", { name: principalName(g) }),
            description: t("They'll lose their access to it right away. You can give it back later."),
            confirmText: t("Remove"),
            destructive: true,
          },
    );
    // Once you have left, there is nothing more here for you to see, nor loaded inside it
    if (ok)
      remove.mutate(g.id, {
        onSuccess: () => {
          if (!self) return;
          void refreshFiles(qc, { left: [nodeId] });
          onClose();
        },
      });
  };

  const info = q.data;
  const personalRoot = info?.drive.kind === "personal" && info.is_drive_root;
  const roles: Role[] = info?.is_drive_root && info.drive.kind === "team" ? ["viewer", "contributor", "editor", "manager", "owner"] : ["viewer", "contributor", "editor", "manager"];
  const guestRoles = roles.filter((r) => !atLeast(r, "manager"));
  const effectiveRole = principal?.guest && atLeast(role, "manager") ? "editor" : role;
  const maxDays = info?.guest_max_days ?? 90;
  const effectiveDays = principal?.guest ? Math.min(days || 7, maxDays) : days;
  const expiryOptions = EXPIRY.filter((x) => !principal?.guest || (x.days > 0 && x.days <= maxDays));
  if (principal?.guest && !expiryOptions.some((x) => x.days === maxDays)) expiryOptions.push({ label: t("{n} day|{n} days", { n: maxDays }), days: maxDays });
  const title = info ? (info.is_drive_root ? t("Members of “{name}”", { name: info.drive.name }) : t("Share “{name}”", { name: info.node.name })) : t("Manage access");

  return (
    <Dialog open onOpenChange={(o) => !o && onClose()}>
      <DialogContent className="sm:max-w-lg">
        {question}
        <DialogHeader>
          <DialogTitle className="truncate pr-8">{title}</DialogTitle>
          <DialogDescription>
            {info?.is_drive_root
              ? t("Members can access all files in this space.")
              : t("People you share with can access this item (for a folder, everything in it). It appears in their Shared with me.")}
          </DialogDescription>
        </DialogHeader>

        {!info ? (
          <Pending
            query={q}
            compact
            loading={
              <div className="flex h-32 items-center justify-center text-muted-foreground">
                <Loader2Icon className="size-5 animate-spin" />
              </div>
            }
          />
        ) : personalRoot ? (
          <p className="rounded-md bg-muted/60 p-3 text-sm text-muted-foreground">{t("A personal space can't be shared as a whole. Right-click a folder in it and choose Share with….")}</p>
        ) : (
          <>
            {info.can_manage && (
              <form
                className="grid gap-2"
                onSubmit={(e) => {
                  e.preventDefault();
                  if (!principal) return;
                  add.mutate({
                    principal_type: principal.principal_type,
                    principal_id: principal.principal_id,
                    role: effectiveRole,
                    expires_at: effectiveDays ? Math.floor(Date.now() / 1000) + effectiveDays * 86400 : null,
                  });
                }}
              >
                {/* On a phone, the person or group on a line of its own */}
                <div className="flex flex-wrap items-start gap-2 sm:flex-nowrap">
                  <PrincipalPicker value={principal} onChange={setPrincipal} allowEveryone={info.drive.kind !== "personal" && (!info.share_own_groups || me.role === "admin")} />
                  <NativeSelect size="sm" value={effectiveRole} onChange={(e) => setRole(e.target.value as Role)} aria-label={t("Role")}>
                    {(principal?.guest ? guestRoles : roles).map((r) => (
                      <option key={r} value={r}>
                        {ROLE_LABEL[r]}
                      </option>
                    ))}
                  </NativeSelect>
                  <NativeSelect size="sm" value={effectiveDays} onChange={(e) => setDays(Number(e.target.value))} aria-label={tc("short", "Expiration")}>
                    {expiryOptions.map((x) => (
                      <option key={x.days} value={x.days}>
                        {x.label}
                      </option>
                    ))}
                  </NativeSelect>
                  <Button type="submit" size="sm" className="h-8" disabled={!principal || add.isPending}>
                    {add.isPending && <Loader2Icon className="animate-spin" />}
                    {t("Add")}
                  </Button>
                </div>
                <p className="text-xs text-muted-foreground">{t("{role}: {hint}", { role: ROLE_LABEL[effectiveRole], hint: ROLE_HINT[effectiveRole] })}</p>
                {principal?.guest && (
                  <p className="text-xs text-muted-foreground">{t("Guest access requires an end date within {n} days, including for groups with guests.", { n: maxDays })}</p>
                )}
                {info.share_own_groups && me.role !== "admin" && (
                  <p className="text-xs text-muted-foreground">{t("New and changed access can only be given within your current groups. Existing grants are kept.")}</p>
                )}
                <ErrorText>{add.error?.message}</ErrorText>
              </form>
            )}

            <div className="max-h-[50vh] overflow-y-auto">
              <div className="divide-y">
                {info.direct.map((g) => {
                  const self = g.principal_type === "user" && g.principal_id === me.id;
                  const canLeave = self && g.role !== "owner" && !info.is_drive_root;
                  return (
                    <GrantRow
                      key={g.id}
                      g={g}
                      roles={g.guest ? guestRoles : roles}
                      editable={info.can_manage}
                      onRole={(r) => add.mutate({ principal_type: g.principal_type, principal_id: g.principal_id, role: r, expires_at: g.expires_at })}
                      onExpiry={(expiry) => add.mutate({ principal_type: g.principal_type, principal_id: g.principal_id, role: g.role, expires_at: expiry })}
                      maxDays={maxDays}
                      pending={add.isPending}
                      onRemove={info.can_manage || canLeave ? () => confirmRemove(g, self) : undefined}
                      removeLabel={canLeave && !info.can_manage ? t("Leave") : t("Remove")}
                    />
                  );
                })}
                {info.direct.length === 0 && info.inherited.length === 0 && <p className="py-4 text-center text-sm text-muted-foreground">{t("Not shared with anyone yet")}</p>}
              </div>
              {info.inherited.length > 0 && (
                <>
                  <div className="mt-3 mb-1 text-xs font-medium text-muted-foreground">{t("Inherited (managed in a parent folder or the space)")}</div>
                  <div className={cn("divide-y opacity-80")}>
                    {info.inherited.map((g) => (
                      <GrantRow key={`i${g.id}`} g={g} roles={roles} editable={false} />
                    ))}
                  </div>
                </>
              )}
            </div>
            {info.is_drive_root && <LinkMakersSetting driveId={info.drive.id} value={info.drive.link_makers} canChoose={info.can_manage} />}
            {!info.can_manage && (
              <p className="text-xs text-muted-foreground">
                {atLeast(info.my_role, "manager") && !me.can_share
                  ? t("Your account isn't allowed to share, so you can't change who has access. Ask an administrator.")
                  : t("Your role is “{role}”. Only managers can change access.", { role: info.my_role ? ROLE_LABEL[info.my_role] : "—" })}
              </p>
            )}
          </>
        )}
      </DialogContent>
    </Dialog>
  );
}
